"""Regenerate the results tables in `README.md`.

Everything between the BEGIN and END results markers in `README.md` is replaced.
"""

import re
import sys
from collections import defaultdict
from pathlib import Path
from statistics import median

from rail_runtime import curves, slowzones
from rail_runtime import model as m
from rail_runtime import multitrain as mt
from rail_runtime.curves import Ranking
from rail_runtime.multitrain import BusyRow

KINDS = ["posted", "60", "80", "100"]
SPEEDS = {"posted": "posted", "60": "60 mph", "80": "80 mph", "100": "100 mph"}
README = Path(__file__).resolve().parents[2] / "README.md"
BEGIN = "<!-- BEGIN results: generated by rail_runtime.results, do not edit by hand -->"
END = "<!-- END results -->"


def table(head: list[str], rows: list[list[str]], align: list[str] | None = None) -> str:
    align = align or ["l"] + ["r"] * (len(head) - 1)
    sep = ["---:" if a == "r" else "---" for a in align]
    lines = ["| " + " | ".join(head) + " |", "| " + " | ".join(sep) + " |"]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def f1(x: float) -> str:
    return "" if x != x else f"{x:.1f}"


def short(name: str) -> str:
    return (
        name.replace(" Station", "")
        .replace(" Terminal", "")
        .replace("Grand Central", "GCM")
        .replace("Mets-Willets Point", "Mets")
        .replace("Flushing Main Street", "Flushing")
    )


def pattern(stops: list[str], line_stops: list[str], only_express: bool = False) -> str:
    """Label a stopping pattern by its origin and the stations it skips.

    With `only_express`, the line has one express pattern, so it's just "express".
    """
    order = [s for s in reversed(line_stops)]
    first = order.index(stops[0])
    skipped = [s for s in order[first:] if s not in stops]
    if not skipped:
        return f"{short(stops[0])}, all stops"
    if only_express:
        return f"{short(stops[0])}, express"
    if len(stops) == 2:
        return f"{short(stops[0])}, nonstop"
    via = stops[1:-1]
    if len(via) < len(skipped):
        return f"{short(stops[0])}, stops at {', '.join(short(s) for s in via)}"
    return f"{short(stops[0])}, skips {', '.join(short(s) for s in skipped)}"


def timetable(data: str, date: str) -> str:
    out: list[str] = []
    m7 = m.TRAINS[0]
    for spec in mt.SPECS.values():
        line, stops, route = spec.line(data), spec.stops, spec.route
        order = list(reversed(stops))
        trips = m.am_inbound(f"{data}/gtfs", date, None if route else stops[-1], set(stops), route, stops[0])
        by = defaultdict(list)
        for t in trips:
            by[tuple(s for s in order if s in t.stops)].append(t.sched)
        rows = []
        only_express = sum(len(p) < len(stops) for p in by) == 1
        for pat, sch in sorted(by.items(), key=lambda kv: (-len(kv[1]), kv[0])):
            sims = [line.trip(m7, k, list(pat)) for k in KINDS]
            label = pattern(list(pat), stops, only_express)
            rows.append([label, str(len(sch)), f"{median(sch):.0f}", *map(f1, sims)])
        out.append(
            f"#### {short(stops[-1])} - {short(stops[0])}\n\n"
            + table(["Pattern", "Trips", "Scheduled", "Posted", "60 mph", "80 mph", "100 mph"], rows)
        )
    return "\n\n".join(out)


def trains(data: str, every: bool = False) -> str:
    out: list[str] = []
    for name, spec in mt.SPECS.items():
        line, pats = spec.line(data), spec.patterns
        for pname, p in pats.items():
            rows = [[tr.name, *(f1(line.trip(tr, k, p)) for k in KINDS)] for tr in m.trains(every)]
            out.append(f"#### {name} {pname}\n\n" + table(["Train", "Posted", "60 mph", "80 mph", "100 mph"], rows))
    return "\n\n".join(out)


def busy(data: str) -> str:
    out: list[str] = []
    setups = list(mt.lines(data).values())
    for (title, _, cases, _, _), busy_rows in zip(setups, mt.busy(setups), strict=True):
        res: defaultdict[tuple[str, str], dict[str, BusyRow]] = defaultdict(dict)
        for r in busy_rows:
            res[(r.service, r.kind)][r.train.supply] = r
        rows: list[list[str]] = []
        services = list(dict.fromkeys(c.name for c in cases))
        for (service, kind), by in sorted(
            res.items(), key=lambda kv: (services.index(kv[0][0]), KINDS.index(kv[0][1]))
        ):
            m7, m8 = by["third rail"], by["25 kV"]
            rows.append(
                [
                    service if kind == "posted" else "",
                    SPEEDS[kind],
                    f1(m7.one),
                    f1(m7.no_regen),
                    f1(m7.regen),
                    f1(m8.regen),
                    f"{m7.vmin:.0f}",
                ]
            )
        out.append(
            f"#### {title}\n\n"
            + table(
                ["Service", "Speeds", "M7, 1 train", "M7, busy", "M7, busy + regen", "M8 25 kV", "Lowest V (M7)"], rows
            )
        )
    return "\n\n".join(out)


def ranking(rank: Ranking) -> str:
    out: list[str] = []
    for name, base, rows in rank:
        pats = list(base)
        head = ["From mi", "To mi", "Near"]
        zones = any(z.posted is not None for z in rows)
        head += ["Posted", "Raised to"] if zones else ["Allows"]
        head += [f"{p} saves" for p in pats]
        body: list[list[str]] = []
        for z in rows:
            mid = [f"{z.allows:.0f} mph"] if z.posted is None else [f"{z.posted:.0f} mph", f"{z.allows:.0f} mph"]
            body.append([f"{z.start:.2f}", f"{z.end:.2f}", z.near, *mid, *(f"{z.saved[p] * 60:.0f} s" for p in pats)])
        basis = ", ".join(f"{p} {v:.1f} min" for p, v in base.items())
        out.append(
            f"#### {name} (base: {basis})\n\n"
            + (table(head, body, ["r", "r", "l"] + ["r"] * (len(head) - 3)) if body else "None costs 3 s or more.")
        )
    return "\n\n".join(out)


def main(data: str, date: str = "20261027", every: bool = False) -> None:
    print("timetable", file=sys.stderr, flush=True)
    sections = [
        (
            "Timetable vs. model",
            f"AM inbound trips arriving at Penn, GCM or Atlantic, or Jamaica from beyond it, 6-10 AM "
            f"on {date[:4]}-{date[4:6]}-{date[6:]}, "
            "grouped by stopping pattern: median scheduled minutes vs. one M7 running flat out "
            "on 750 V third rail with 30 s dwells.",
            timetable(data, date),
        ),
    ]
    print("trains", file=sys.stderr, flush=True)
    sections.append(("Trains", "One train alone, minutes.", trains(data, every)))
    print("busy service", file=sys.stderr, flush=True)
    sections.append(
        (
            "Busy service",
            "Minutes per inbound trip in steady service, from the time-stepped multi-train simulation. "
            '"Busy" is with the other trains on the line; "+ regen" adds regenerative braking.',
            busy(data),
        )
    )
    print("rankings", file=sys.stderr, flush=True)
    sections.append(
        (
            "Posted slow zones",
            "One M7, raising one posted zone at a time to what the curves allow (80 mph cap).",
            ranking(slowzones.rank(data)),
        )
    )
    sections.append(
        (
            "Limiting curves",
            "One M7 at an 80 mph cap, easing one curve-limited zone at a time to 80 mph.",
            ranking(curves.rank(data)),
        )
    )
    text = "\n\n".join(f"### {h}\n\n{intro}\n\n{body}" for h, intro, body in sections)
    readme = README.read_text()
    block = f"{BEGIN}\n\n{text}\n\n{END}"
    if BEGIN in readme:
        readme = re.sub(re.escape(BEGIN) + ".*?" + re.escape(END), lambda _: block, readme, flags=re.S)
    else:
        readme = readme.rstrip("\n") + "\n\n## Results\n\n" + block + "\n"
    README.write_text(readme)
