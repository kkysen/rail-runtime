"""Regenerate the results tables in `README.md`.

Everything between the BEGIN and END results markers in `README.md` is replaced.
"""

import re
import sys
from collections import defaultdict
from functools import cache
from pathlib import Path
from statistics import median

from rail_runtime import curves, slowzones
from rail_runtime import model as m
from rail_runtime import multitrain as mt
from rail_runtime.curves import Ranking
from rail_runtime.multitrain import BusyRow

KINDS = ["posted", "60", "80", "100"]
SPEEDS = {"posted": "posted", "60": "60 mph", "80": "80 mph", "100": "100 mph"}
README = Path(__file__).resolve().parents[2] / "README.md"
BEGIN = "<!-- BEGIN results: generated by rail_runtime.results, do not edit by hand -->"
END = "<!-- END results -->"


def table(head: list[str], rows: list[list[str]], align: list[str] | None = None) -> str:
    align = align or ["l"] + ["r"] * (len(head) - 1)
    sep = ["---:" if a == "r" else "---" for a in align]
    lines = ["| " + " | ".join(head) + " |", "| " + " | ".join(sep) + " |"]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def f1(x: float) -> str:
    return "" if x != x else f"{x:.1f}"


def short(name: str, railroad: str = "LIRR") -> str:
    if name == "Grand Central":  # the LIRR's Grand Central Madison, or Metro-North's Grand Central Terminal
        return "GCM" if railroad == "LIRR" else "GCT"
    return (
        name.strip()  # Metro-North's GTFS has "Mt Vernon East "
        .replace(" Station", "")
        .replace(" Terminal", "")
        .replace("Mets-Willets Point", "Mets")
        .replace("Flushing Main Street", "Flushing")
    )


def heading(name: str, spec: mt.Spec) -> str:
    """The line's ends, and its route when a branch has several, like `Babylon via Atlantic Branch - Jamaica`."""
    end = name if spec.via else short(spec.stops[-1], spec.railroad)
    return f"{end} - {short(spec.stops[0], spec.railroad)}"


def pattern(stops: list[str], line_stops: list[str], only_express: bool = False) -> str:
    """Label a stopping pattern by its origin and the stations it skips.

    With `only_express`, the line has one express pattern, so it's just "express".
    """
    order = [s for s in reversed(line_stops)]
    first = order.index(stops[0])
    skipped = [s for s in order[first:] if s not in stops]
    if not skipped:
        return f"{short(stops[0])}, all stops"
    if only_express:
        return f"{short(stops[0])}, express"
    if len(stops) == 2:
        return f"{short(stops[0])}, nonstop"
    via = stops[1:-1]
    if len(via) < len(skipped):
        return f"{short(stops[0])}, stops at {', '.join(short(s) for s in via)}"
    return f"{short(stops[0])}, skips {', '.join(short(s) for s in skipped)}"


@cache
def schedules(data: str, date: str) -> dict[str, dict[tuple[str, ...], list[float]]]:
    """Per line, the scheduled minutes of its AM inbound trips, by stopping pattern in inbound order."""
    out: dict[str, dict[tuple[str, ...], list[float]]] = {}
    for name, spec in mt.SPECS.items():
        stops, route = spec.stops, spec.route
        order = list(reversed(stops))
        trips = m.am_inbound(
            spec.gtfs(data), date, None if route else stops[-1], set(stops), route, stops[0], via=spec.via
        )
        by: defaultdict[tuple[str, ...], list[float]] = defaultdict(list)
        for t in trips:
            by[tuple(s for s in order if s in t.stops)].append(t.sched)
        out[name] = dict(by)
    return out


def scheduled(data: str, date: str, name: str, pat: list[str]) -> str:
    """Median scheduled minutes of line `name`'s trips on inbound pattern `pat`; blank if none run it."""
    sch = schedules(data, date)[name].get(tuple(pat))
    return f"{median(sch):.0f}" if sch else ""


def timetable(data: str, date: str) -> str:
    out: list[str] = []
    for name, spec in mt.SPECS.items():
        line, stops = spec.line(data), spec.stops
        m7 = spec.trains()[0]
        by = schedules(data, date)[name]
        rows = []
        only_express = sum(len(p) < len(stops) for p in by) == 1
        for pat, sch in sorted(by.items(), key=lambda kv: (-len(kv[1]), kv[0])):
            sims = [line.trip(m7, k, list(pat)) for k in KINDS]
            label = pattern(list(pat), stops, only_express)
            rows.append([label, str(len(sch)), f"{median(sch):.0f}", *map(f1, sims)])
        out.append(
            f"#### {heading(name, spec)}\n\n"
            + table(["Pattern", "Trips", "Scheduled", "Posted", "60 mph", "80 mph", "100 mph"], rows)
        )
    return "\n\n".join(out)


def trains(data: str, date: str, every: bool = False) -> str:
    out: list[str] = []
    for name, spec in mt.SPECS.items():
        line, pats = spec.line(data), spec.patterns
        for pname, p in pats.items():
            sch = scheduled(data, date, name, p)
            rows = [
                [tr.name, sch if i == 0 else "", *(f1(line.trip(tr, k, p)) for k in KINDS)]
                for i, tr in enumerate(spec.trains(every))
            ]
            out.append(
                f"#### {name} {pname}\n\n"
                + table(["Train", "Scheduled", "Posted", "60 mph", "80 mph", "100 mph"], rows)
            )
    return "\n\n".join(out)


def busy(data: str, date: str) -> str:
    out: list[str] = []
    named = mt.lines(data)
    setups = list(named.values())
    for key, (title, _, cases, _, _, (dc, ac)), busy_rows in zip(named, setups, mt.busy(setups), strict=True):
        name = "Port Washington" if key.startswith("PW") else key
        inbound = {c.name: c.stops[::-1] for c in cases if c.inbound}
        res: defaultdict[tuple[str, str], dict[str, BusyRow]] = defaultdict(dict)
        for r in busy_rows:
            res[(r.service, r.kind)][r.train.supply] = r
        rows: list[list[str]] = []
        services = list(dict.fromkeys(c.name for c in cases))
        for (service, kind), by in sorted(
            res.items(), key=lambda kv: (services.index(kv[0][0]), KINDS.index(kv[0][1]))
        ):
            m7, m8 = by["third rail"], by["AC"]
            rows.append(
                [
                    service if kind == "posted" else "",
                    scheduled(data, date, name, inbound[service]) if kind == "posted" else "",
                    SPEEDS[kind],
                    f1(m7.one),
                    f1(m7.no_regen),
                    f1(m7.regen),
                    f1(m8.regen),
                    "" if m7.vmin != m7.vmin else f"{m7.vmin:.0f}",
                ]
            )
        # Each train by its type: "M7" or "M8", and the AC one with its voltage, like "M8 25 kV".
        t, a = dc.name.split(",")[0], ac.name.replace(",", "")
        out.append(
            f"#### {title}\n\n"
            + table(
                [
                    "Service",
                    "Scheduled",
                    "Speeds",
                    f"{t}, 1 train",
                    f"{t}, busy",
                    f"{t}, busy + regen",
                    a,
                    f"Lowest V ({t})",
                ],
                rows,
            )
        )
    return "\n\n".join(out)


def ranking(rank: Ranking) -> str:
    out: list[str] = []
    for name, base, rows in rank:
        pats = list(base)
        head = ["From mi", "To mi", "Near"]
        zones = any(z.posted is not None for z in rows)
        head += ["Posted", "Raised to"] if zones else ["Allows"]
        head += [f"{p} saves" for p in pats]
        body: list[list[str]] = []
        for z in rows:
            mid = [f"{z.allows:.0f} mph"] if z.posted is None else [f"{z.posted:.0f} mph", f"{z.allows:.0f} mph"]
            body.append([f"{z.start:.2f}", f"{z.end:.2f}", z.near, *mid, *(f"{z.saved[p] * 60:.0f} s" for p in pats)])
        basis = ", ".join(f"{p} {v:.1f} min" for p, v in base.items())
        out.append(
            f"#### {name} (base: {basis})\n\n"
            + (table(head, body, ["r", "r", "l"] + ["r"] * (len(head) - 3)) if body else "None costs 3 s or more.")
        )
    return "\n\n".join(out)


def main(data: str, date: str = "20261027", every: bool = False) -> None:
    print("timetable", file=sys.stderr, flush=True)
    sections = [
        (
            "Timetable vs. model",
            f"AM inbound trips arriving at Penn, GCM or Atlantic, or Jamaica from beyond it, "
            "or on Metro-North at GCT, or Stamford from New Canaan, 6-10 AM "
            f"on {date[:4]}-{date[4:6]}-{date[6:]}, "
            "grouped by stopping pattern: median scheduled minutes vs. one train running flat out with 30 s dwells: "
            "an M7 on the LIRR's 750 V third rail, an M7A on Metro-North's 700 V, "
            "or on the New Haven Line, an M8 on that third rail to Pelham and 12.5 kV catenary beyond.",
            timetable(data, date),
        ),
    ]
    print("trains", file=sys.stderr, flush=True)
    sections.append(
        (
            "Trains",
            "One train alone, minutes, next to the median scheduled for trips with that stopping pattern, if any.",
            trains(data, date, every),
        )
    )
    print("busy service", file=sys.stderr, flush=True)
    sections.append(
        (
            "Busy service",
            "Minutes per inbound trip in steady service, from the time-stepped multi-train simulation. "
            '"Busy" is with the other trains on the line; "+ regen" adds regenerative braking. '
            '"Scheduled" is the median for trips with that stopping pattern, if any.',
            busy(data, date),
        )
    )
    print("rankings", file=sys.stderr, flush=True)
    sections.append(
        (
            "Posted slow zones",
            "One train, the timetable's, raising one posted zone at a time to what the curves allow (80 mph cap).",
            ranking(slowzones.rank(data)),
        )
    )
    sections.append(
        (
            "Limiting curves",
            "One train, the timetable's, at an 80 mph cap, easing one curve-limited zone at a time to 80 mph.",
            ranking(curves.rank(data)),
        )
    )
    text = "\n\n".join(f"### {h}\n\n{intro}\n\n{body}" for h, intro, body in sections)
    readme = README.read_text()
    block = f"{BEGIN}\n\n{text}\n\n{END}"
    if BEGIN in readme:
        readme = re.sub(re.escape(BEGIN) + ".*?" + re.escape(END), lambda _: block, readme, flags=re.S)
    else:
        readme = readme.rstrip("\n") + "\n\n## Results\n\n" + block + "\n"
    README.write_text(readme)
